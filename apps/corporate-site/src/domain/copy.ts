export const t = (key: CopyKey, values: Record<string, string | number> = {}) =>
  dictionaries[activeLocale()][key].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? ''),
  );

const ruWeeks: Partial<Record<Intl.LDMLPluralRule, string>> = {
  one: 'неделя',
  few: 'недели',
  many: 'недель',
};
const ruPlural = new Intl.PluralRules('ru');

export const fromWeeks = (n: number) =>
  activeLocale() === Locale.En
    ? `from ${n} ${n === 1 ? 'week' : 'weeks'}`
    : `от ${n} ${n % 10 === 1 && n % 100 !== 11 ? 'недели' : 'недель'}`;

export const weeks = (n: number) =>
  activeLocale() === Locale.En
    ? `${n} ${n === 1 ? 'week' : 'weeks'}`
    : `${n} ${ruWeeks[ruPlural.select(n)] ?? 'недель'}`;
